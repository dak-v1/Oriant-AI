"use client";
/**
 * PackageDrawer — "Review generated package" (spec §14): wide drawer with
 * the fixture artifacts in the tabbed CodeViewer, a quiet summary of the
 * integration manifest, and the honest simulated-output note.
 */
import { useMemo } from "react";
import { FlaskConical, Plug2 } from "lucide-react";
import Drawer from "@/components/mock/ui/Drawer";
import CodeViewer from "@/components/mock/ui/CodeViewer";
import type { ArtifactFile } from "@/lib/mock/types";
import { BUILD_FIXTURES } from "@/lib/mock/fixtures/build-artifacts";
import { AGENT_NAME } from "@/lib/mock/fixtures/ids";
import { INTEGRATIONS } from "@/lib/mock/fixtures/integrations";
import styles from "./build.module.css";

interface ManifestConnection {
  id: string;
  mode?: string;
  account?: string;
}

interface ManifestTool {
  id: string;
  server?: string;
}

interface ManifestSummary {
  connections: ManifestConnection[];
  mcpTools: ManifestTool[];
}

/** Read the manifest artifact back out of the fixture (content stays fixture-owned). */
function parseManifest(files: ArtifactFile[]): ManifestSummary | null {
  const file = files.find((f) => f.name === "integration-manifest.json");
  if (!file) return null;
  try {
    const data = JSON.parse(file.content) as Partial<ManifestSummary>;
    return { connections: data.connections ?? [], mcpTools: data.mcpTools ?? [] };
  } catch {
    return null;
  }
}

const prettyMode = (mode?: string) => (mode ? mode.replace(/_/g, " ") : "");

export default function PackageDrawer({
  open,
  agentId,
  onClose,
}: {
  open: boolean;
  agentId: string | null;
  onClose: () => void;
}) {
  const fixture = agentId ? BUILD_FIXTURES[agentId] : undefined;
  const name = agentId ? AGENT_NAME[agentId] ?? agentId : "";
  const manifest = useMemo(() => (fixture ? parseManifest(fixture.artifacts) : null), [fixture]);

  return (
    <Drawer
      open={open && Boolean(fixture)}
      onClose={onClose}
      title={name}
      eyebrow="Generated package"
      wide
      footer={
        <button type="button" className="oa-btn oa-btn--ghost" onClick={onClose}>
          Close
        </button>
      }
    >
      {fixture && (
        <div style={{ display: "grid", gap: 20 }}>
          <span className="oa-sim-note">
            <FlaskConical size={12} aria-hidden />
            Generated by the Agent Factory (simulated output).
          </span>

          <CodeViewer files={fixture.artifacts} maxHeight={380} />

          {manifest && (manifest.connections.length > 0 || manifest.mcpTools.length > 0) && (
            <section style={{ display: "grid", gap: 10 }} aria-label="Integration manifest summary">
              <div style={{ display: "grid", gap: 3 }}>
                <h3 className="oa-h3">
                  <Plug2 size={14} aria-hidden style={{ marginRight: 6, verticalAlign: -2 }} />
                  Integration manifest
                </h3>
                <p className="oa-sub">
                  What this package is wired to use once connections are approved; nothing connects
                  during the demo.
                </p>
              </div>

              <div className={styles.manifestList}>
                {manifest.connections.map((c) => (
                  <div key={c.id} className={`oa-panel ${styles.manifestRow}`}>
                    <div style={{ display: "grid", gap: 2, minWidth: 0 }}>
                      <p className={styles.manifestName}>{INTEGRATIONS[c.id]?.name ?? c.id}</p>
                      {c.account && <p className={styles.manifestSub}>{c.account}</p>}
                    </div>
                    {c.mode && <span className="oa-tag oa-tag--neutral">{prettyMode(c.mode)}</span>}
                  </div>
                ))}
                {manifest.mcpTools.map((t) => (
                  <div key={t.id} className={`oa-panel ${styles.manifestRow}`}>
                    <div style={{ display: "grid", gap: 2, minWidth: 0 }}>
                      <p className={styles.manifestName}>{INTEGRATIONS[t.id]?.name ?? t.id}</p>
                      {t.server && <p className={styles.manifestSub}>{t.server}</p>}
                    </div>
                    <span className="oa-tag oa-tag--teal">MCP tool</span>
                  </div>
                ))}
              </div>
            </section>
          )}
        </div>
      )}
    </Drawer>
  );
}
